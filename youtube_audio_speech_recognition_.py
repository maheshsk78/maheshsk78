import re

def is_youtube_url(url: str) -> bool:
    """
    Validates if a given URL is a YouTube video URL.
    """
    youtube_regex = (
        r"(https?://)?(www\.)?"  # Optional http(s):// or www.
        r"(youtube\.com|youtu\.be)/"  # youtube.com or youtu.be
        r"(watch\?v=|embed/|v/|)([\w-]{11})"  # Video ID part
    )
    match = re.match(youtube_regex, url)
    return bool(match)

