from pytubefix import YouTube
import os

def download_audio_pytubefix(url, destination='./'):
    """
    Downloads the audio stream from a YouTube video using pytubefix and saves it as an MP3.
    """
    try:
        yt = YouTube(url)
        # Filter for the best audio stream
        audio_stream = yt.streams.get_audio_only()

        print(f"Downloading audio for: {yt.title}...")

        # Download the file
        out_file = audio_stream.download(output_path=destination)

        # Rename the file to have an .mp3 extension
        base, ext = os.path.splitext(out_file)
        new_file = base + '.mp3'
        os.rename(out_file, new_file)

        print(f"Successfully downloaded: {os.path.basename(new_file)}")
        return new_file # Return the full path as a string

    except Exception as e:
        print(f"An error occurred: {e}")

